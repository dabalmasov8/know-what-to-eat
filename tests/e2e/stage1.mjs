import { launch, check, BASE } from './lib.mjs';
const { browser, page, errors } = await launch();
await page.goto(BASE);
await page.click('text=Set up');
await page.waitForSelector('#nameA');
await page.fill('#nameA', 'Anna');
await page.fill('#nameB', 'Max');
await page.fill('#postcode', '00999');
check('postcode auto-formatted', (await page.inputValue('#postcode')) === '00-999');
await page.fill('#postcode', '0099');
await page.click('button[type=submit]');
check('invalid postcode shows error', await page.isVisible('#pc-err .err'));
await page.fill('#postcode', '00-001');
await page.fill('#radius', '4');
await page.click('text=Delivery / pickup');
await page.click('button[type=submit]');
await page.waitForTimeout(400);
const saved = await page.evaluate(async () => {
  const req = indexedDB.open('food-picker');
  return await new Promise((res) => { req.onsuccess = () => { const g = req.result.transaction('settings').objectStore('settings').get('main'); g.onsuccess = () => res(g.result); }; });
});
check('saved to IndexedDB', saved?.postcode === '00-001' && saved.radius_km === 4 && saved.mode === 'delivery' && saved.names[0] === 'Anna');
await page.reload();
await page.waitForSelector('h1');
check('survives reload', (await page.textContent('main')).includes('00-001'));
await page.goto(BASE + '/#/settings');
await page.waitForSelector('#postcode');
check('settings prefilled', (await page.inputValue('#postcode')) === '00-001' && (await page.inputValue('#radius')) === '4');
await page.screenshot({ path: 'e2e-shots/stage1.png' });
check('no console errors', errors.length === 0);
await browser.close();
