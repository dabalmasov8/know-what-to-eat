import { launch, check, BASE } from './lib.mjs';
const { browser, page, errors } = await launch();
await page.goto(BASE);
await page.click('text=Set up');
await page.fill('#nameA', 'Anna');
await page.fill('#nameB', 'Max');
await page.fill('#postcode', '00-001');
await page.fill('#radius', '5');
await page.click('button[type=submit]');
await page.waitForSelector('#passcode');
check('asks for passcode first', true);
await page.fill('#passcode', 'wrong');
await page.click('text=Unlock');
await page.waitForSelector('.banner.bad, #passcode');
check('wrong passcode rejected', await page.isVisible('#passcode'));
await page.fill('#passcode', 'dev');
await page.click('text=Unlock');
await page.waitForSelector('[data-testid=cuisine-counts]');
const summary = await page.textContent('main');
console.log(summary.replace(/\s+/g, ' ').slice(0, 400));
const items = await page.$$eval('[data-testid=cuisine-counts] li', (els) => els.map((e) => e.textContent));
check('cuisines listed with counts', items.length >= 10 && items.some((t) => t.includes('Georgian')) && items.some((t) => t.includes('Polish')));
const db = await page.evaluate(async () => {
  const req = indexedDB.open('food-picker');
  const db = await new Promise((r) => (req.onsuccess = () => r(req.result)));
  const all = (s) => new Promise((r) => { const g = db.transaction(s).objectStore(s).getAll(); g.onsuccess = () => r(g.result); });
  return { places: await all('places'), area: await all('area') };
});
check('no place below 4.5 or 30 reviews stored', db.places.every((p) => p.rating >= 4.5 && p.rating_count >= 30));
check('"Hidden Gem 5.0" (3 reviews) excluded', !db.places.some((p) => p.name.includes('Hidden Gem')));
check('far away place excluded by radius', !db.places.some((p) => p.name === 'Far Away Pasta'));
check('area stored with place_ids', db.area[0].place_ids.length === db.places.length);
console.log('stats', JSON.stringify(db.area[0].stats));
await page.selectOption('main select', 'italian');
await page.click('text=Search >> nth=-1');
await page.waitForSelector('[role=status]:has-text("new place"), [role=status]:has-text("No new places")');
check('targeted search shows a result message', true);
await page.screenshot({ path: 'e2e-shots/stage15.png', fullPage: true });
// Small radius => sparse warning
await page.goto(BASE + '/#/settings');
await page.fill('#radius', '1');
await page.click('button[type=submit]');
await page.waitForSelector('[data-testid=cuisine-counts], .banner.warn');
const text = await page.textContent('main');
check('sparse area suggests larger radius', /larger radius|Try a bigger radius/.test(text) || (await page.$$eval('[data-testid=cuisine-counts] li', (e) => e.length)) > 0);
console.log(text.replace(/\s+/g, ' ').slice(0, 300));
check('no console errors', errors.filter((e) => !/401|404/.test(e)).length === 0);
if (errors.length) console.log(errors);
await browser.close();
