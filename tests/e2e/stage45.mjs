import { launch, check, setupApp, answerAll } from './lib.mjs';
const { browser, page, errors } = await launch();
await setupApp(page);
await page.click('text=Start choosing');
await page.waitForSelector('text=Anna, your turn');
await answerAll(page, ['Thai', 'Italian']);
await page.click('text=I’m Max');
await answerAll(page, ['Thai', 'Italian']);
await page.waitForSelector('text=Pick randomly among these');
const apiCalls = [];
page.on('request', (r) => { if (r.url().includes('/api/')) apiCalls.push(r.url()); });
await page.click('button.secondary:has-text("Thai")');
await page.waitForSelector('[data-testid=place-card]');
const cards = await page.$$('[data-testid=place-card]');
check('thai places listed (2 qualifying)', cards.length === 2);
check('places come from local cache (no API calls)', apiCalls.length === 0);
const first = await page.$('[data-testid=place-card]');
const txt = await first.textContent();
check('card shows distance, Google rating, our rating state', /\d+(\.\d)? ?(km|m)/.test(txt) && /Google 4\.\d \(\d+\)/.test(txt) && txt.includes('Not rated by us yet'));
check('card has website, call, maps', (await first.$$('a[href^="http"], a[href^="tel:"]')).length >= 3 && txt.includes('Open in Maps') && txt.includes('Call'));
const hrefs = await first.$$eval('a', (as) => as.map((a) => a.href));
check('delivery buttons for 4 services', ['Wolt', 'Pyszne.pl', 'Glovo', 'Uber Eats'].every((s) => txt.includes(s)));
check('maps link uses official URL format', hrefs.some((h) => h.startsWith('https://www.google.com/maps/search/?api=1&query=') && h.includes('query_place_id=')));
check('open/closed chip present', /Open now|Closed now/.test(txt));
const all = cards.length;
await page.check('input[type=checkbox]');
const open = (await page.$$('[data-testid=place-card]')).length;
check('open-now filter never adds places', open <= all);
await page.uncheck('input[type=checkbox]');
await page.click('button:has-text("Our rating")');
check('sort toggle works', (await page.getAttribute('button:has-text("Our rating")', 'aria-pressed')) === 'true');
await page.screenshot({ path: 'e2e-shots/stage5-card.png', fullPage: true });
await page.click('[data-testid=place-card] >> nth=0 >> button.big');
await page.waitForSelector('text=Enjoy your meal');
const visits = await page.evaluate(async () => {
  const req = indexedDB.open('food-picker');
  const db = await new Promise((r) => (req.onsuccess = () => r(req.result)));
  return await new Promise((r) => { const g = db.transaction('visits').objectStore('visits').getAll(); g.onsuccess = () => r(g.result); });
});
check('visit created, unrated', visits.length === 1 && visits[0].rated === false && visits[0].type === 'dine_in' && !!visits[0].place_name);
check('no console errors', errors.filter((e) => !/401/.test(e)).length === 0);
await browser.close();
